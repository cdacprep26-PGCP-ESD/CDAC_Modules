/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_RTC_Init();
  /* USER CODE BEGIN 2 */
  // Task 2: Keep PD12 ON in the ready state
  HAL_GPIO_WritePin(GPIOD, GPIO_PIN_12, GPIO_PIN_SET);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
	if (button_pressed_flag) {
	  uint32_t current_time = HAL_GetTick();

	  // Check if enough time has passed since the last valid press
	  if ((current_time - last_debounce_time) > DEBOUNCE_DELAY_MS) {

		  // Verify button is actually pressed (filters noise spikes)
		  if (HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_0) == GPIO_PIN_SET) {
			  last_debounce_time = current_time;
			  event_count++;

			  RTC_TimeTypeDef sTime = {0};
			  RTC_DateTypeDef sDate = {0};

			  /* 4. Read RTC (Critical: Must read Time THEN Date to unlock shadow registers) */
			  if (HAL_RTC_GetTime(&hrtc, &sTime, RTC_FORMAT_BIN) != HAL_OK ||
				  HAL_RTC_GetDate(&hrtc, &sDate, RTC_FORMAT_BIN) != HAL_OK) {

				  // Task 7: Invalid RTC state (Red LED ON)
				  HAL_GPIO_WritePin(GPIOD, GPIO_PIN_14, GPIO_PIN_SET);
			  } else {
				  // Clear Error LED on successful read
				  HAL_GPIO_WritePin(GPIOD, GPIO_PIN_14, GPIO_PIN_RESET);

				  /* 5. Store Record in Ring Buffer */
				  event_buffer[buffer_index].event_number = event_count;
				  event_buffer[buffer_index].hours = sTime.Hours;
				  event_buffer[buffer_index].minutes = sTime.Minutes;
				  event_buffer[buffer_index].seconds = sTime.Seconds;
				  event_buffer[buffer_index].date = sDate.Date;
				  event_buffer[buffer_index].month = sDate.Month;
				  event_buffer[buffer_index].year = sDate.Year;

				  buffer_index = (buffer_index + 1) % BUFFER_SIZE;

				  /* Task 4: Blink PD13 (Orange) for 500 ms */
				  HAL_GPIO_WritePin(GPIOD, GPIO_PIN_13, GPIO_PIN_SET);
				  HAL_Delay(500);
				  HAL_GPIO_WritePin(GPIOD, GPIO_PIN_13, GPIO_PIN_RESET);

				  /* 6. Multiples of 5 logic */
				  if (event_count % 5 == 0) {
					  // Blink PD15 (Blue) three times
					  for (int i = 0; i < 3; i++) {
						  HAL_GPIO_WritePin(GPIOD, GPIO_PIN_15, GPIO_PIN_SET);
						  HAL_Delay(200);
						  HAL_GPIO_WritePin(GPIOD, GPIO_PIN_15, GPIO_PIN_RESET);
						  HAL_Delay(200);
					  }
				  }
			  }
		  }
	  }
	  button_pressed_flag = 0; // Clear flag regardless of debounce outcome
	}
  }
  /* USER CODE END 3 */
}

