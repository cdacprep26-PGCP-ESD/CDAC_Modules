/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_DMA_Init();
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_TIM3_Init();
  /* USER CODE BEGIN 2 */
  HAL_ADC_Start_DMA(&hadc1, (uint32_t*)adc_buffer, BUFFER_SIZE);
  HAL_TIM_Base_Start(&htim3);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
	if (!snapshot_mode)
	{
		uint32_t temp_sum = 0;
		uint32_t vref_sum = 0;

		// Average the 16 readings
		// Even indices (0, 2, 4...) are Rank 1 (Temperature)
		// Odd indices (1, 3, 5...) are Rank 2 (VREFINT)
		for (int i = 0; i < BUFFER_SIZE; i += 2)
		{
			temp_sum += adc_buffer[i];
			vref_sum += adc_buffer[i+1];
		}

		float temp_avg = (float)temp_sum / 16.0f;
		float vref_avg = (float)vref_sum / 16.0f;

		// Calculate actual VDDA based on VREFINT reading (12-bit ADC max = 4095)
		current_vdda = (VREFINT_CAL * 4095.0f) / vref_avg;

		// Calculate temperature using the compensated VDDA
		float temp_voltage = (temp_avg * current_vdda) / 4095.0f;
		current_temp_c = ((temp_voltage - V25) / AVG_SLOPE) + 25.0f;

		// Turn off all LEDs to reset state
		HAL_GPIO_WritePin(GPIOD, GPIO_PIN_12 | GPIO_PIN_13 | GPIO_PIN_14 | GPIO_PIN_15, GPIO_PIN_RESET);

		// Temperature thresholds
		if (current_temp_c < 30.0f) {
			HAL_GPIO_WritePin(GPIOD, GPIO_PIN_12, GPIO_PIN_SET); // Green (Cool)
		} else if (current_temp_c < 35.0f) {
			HAL_GPIO_WritePin(GPIOD, GPIO_PIN_13, GPIO_PIN_SET); // Orange (Warm)
		} else if (current_temp_c < 40.0f) {
			HAL_GPIO_WritePin(GPIOD, GPIO_PIN_15, GPIO_PIN_SET); // Blue (Hot)
		} else {
			// Toggle Red LED (PD14) for Over-Temp warning
			HAL_GPIO_TogglePin(GPIOD, GPIO_PIN_14);
		}
	}
	else
	{
		// If in snapshot mode, keep the current LED state (no updates)
	}
	HAL_Delay(100);
  }
  /* USER CODE END 3 */
}

